import { Notice } from '@/components/ui/Notice';

/**
 * Пометка «Данные позиции уточняются» (DESIGN §2.6 п.3): у товара есть строка листа 2
 * с `resolution = 'conflict-attached'`.
 *
 * Значения листа 2 здесь намеренно НЕ показываются (решение координатора 2026-10-05, ТЗ §4 п.4):
 * пока заказчик не определил назначение листов, публиковать расходящиеся цену и характеристики
 * нельзя. Построчное сравнение — только на служебной `/import-report`.
 */
export function ConflictNotice({ className }: { className?: string }) {
  return (
    <Notice tone="warning" title="Данные позиции уточняются" className={className}>
      В прайсе есть расхождение по этой позиции. Окончательные цену и характеристики подтвердит
      менеджер при согласовании заявки.
    </Notice>
  );
}
